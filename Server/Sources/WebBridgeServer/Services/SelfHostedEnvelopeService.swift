import Crypto
import Foundation

enum SelfHostedEnvelopeError: Error, Equatable {
  case invalidRecipientKey
  case invalidEnvelope
  case expired
  case decryptionFailed
  case invalidPayload
}

/// Versioned, per-device encrypted payload carried by APNs in self-hosted
/// mode. The server only needs the recipient public key; the paired iPhone is
/// the only party that holds the corresponding private key.
struct SelfHostedEncryptedEnvelope: Codable, Sendable {
  let schema: String
  let messageID: String
  let createdAt: Int
  let expiresAt: Int
  let ephemeralPublicKey: String
  let ciphertext: String

  func encoded() -> String {
    let data = (try? JSONEncoder().encode(self)) ?? Data()
    return SelfHostedEnvelopeService.base64URLEncoded(data)
  }

  static func decode(_ value: String) -> SelfHostedEncryptedEnvelope? {
    guard let data = SelfHostedEnvelopeService.base64URLDecoded(value) else { return nil }
    return try? JSONDecoder().decode(SelfHostedEncryptedEnvelope.self, from: data)
  }
}

enum SelfHostedEnvelopeService {
  static let schema = "drel.push-envelope.v1"
  private static let sharedInfo = Data("drel.push-envelope.v1".utf8)

  static func seal(
    payload: PushPayload,
    recipientPublicKey: Data,
    messageID: String,
    now: Date = Date()
  ) throws -> SelfHostedEncryptedEnvelope {
    guard recipientPublicKey.count == 32,
      let recipient = try? Curve25519.KeyAgreement.PublicKey(rawRepresentation: recipientPublicKey)
    else { throw SelfHostedEnvelopeError.invalidRecipientKey }

    let createdAt = Int(now.timeIntervalSince1970)
    let ttl = min(max(payload.ttl ?? 3600, 60), 24 * 3600)
    let expiresAt = createdAt + Int(ttl)
    let ephemeral = Curve25519.KeyAgreement.PrivateKey()
    let secret = try ephemeral.sharedSecretFromKeyAgreement(with: recipient)
    let key = secret.hkdfDerivedSymmetricKey(
      using: SHA256.self,
      salt: Data(),
      sharedInfo: associatedData(messageID: messageID, createdAt: createdAt, expiresAt: expiresAt),
      outputByteCount: 32
    )
    guard let plaintext = try? JSONEncoder().encode(payload),
      let sealed = try? AES.GCM.seal(plaintext, using: key),
      let combined = sealed.combined
    else { throw SelfHostedEnvelopeError.invalidPayload }

    return SelfHostedEncryptedEnvelope(
      schema: schema,
      messageID: messageID,
      createdAt: createdAt,
      expiresAt: expiresAt,
      ephemeralPublicKey: base64URLEncoded(ephemeral.publicKey.rawRepresentation),
      ciphertext: base64URLEncoded(combined)
    )
  }

  static func open(
    _ envelope: SelfHostedEncryptedEnvelope,
    recipientPrivateKey: Curve25519.KeyAgreement.PrivateKey,
    now: Date = Date()
  ) throws -> PushPayload {
    guard envelope.schema == schema,
      envelope.expiresAt > Int(now.timeIntervalSince1970),
      let ephemeralData = base64URLDecoded(envelope.ephemeralPublicKey),
      let ciphertext = base64URLDecoded(envelope.ciphertext),
      let ephemeral = try? Curve25519.KeyAgreement.PublicKey(rawRepresentation: ephemeralData),
      let sealed = try? AES.GCM.SealedBox(combined: ciphertext)
    else {
      throw envelope.expiresAt <= Int(now.timeIntervalSince1970)
        ? SelfHostedEnvelopeError.expired
        : SelfHostedEnvelopeError.invalidEnvelope
    }
    let secret = try recipientPrivateKey.sharedSecretFromKeyAgreement(with: ephemeral)
    let key = secret.hkdfDerivedSymmetricKey(
      using: SHA256.self,
      salt: Data(),
      sharedInfo: associatedData(
        messageID: envelope.messageID,
        createdAt: envelope.createdAt,
        expiresAt: envelope.expiresAt
      ),
      outputByteCount: 32
    )
    guard let plaintext = try? AES.GCM.open(sealed, using: key),
      let payload = try? JSONDecoder().decode(PushPayload.self, from: plaintext)
    else {
      throw SelfHostedEnvelopeError.decryptionFailed
    }
    return payload
  }

  /// Performs only structural validation. The relay intentionally cannot
  /// decrypt this object: it is generated by the sender and opened solely by
  /// the paired iPhone's notification extension.
  static func validatePassthroughEnvelope(
    _ encoded: String,
    now: Date = Date()
  ) -> SelfHostedEncryptedEnvelope? {
    // APNs allows a 4 KB payload. Leave room for aps, IDs, and JSON keys.
    guard encoded.utf8.count <= 3_200,
      let envelope = SelfHostedEncryptedEnvelope.decode(encoded),
      envelope.schema == schema,
      !envelope.messageID.isEmpty,
      envelope.messageID.utf8.count <= 128,
      envelope.expiresAt > Int(now.timeIntervalSince1970),
      envelope.expiresAt - envelope.createdAt > 0,
      envelope.expiresAt - envelope.createdAt <= 24 * 3600,
      let ephemeral = base64URLDecoded(envelope.ephemeralPublicKey),
      ephemeral.count == 32,
      let ciphertext = base64URLDecoded(envelope.ciphertext),
      ciphertext.count >= 28,
      (try? AES.GCM.SealedBox(combined: ciphertext)) != nil
    else { return nil }
    return envelope
  }

  static func base64URLEncoded(_ data: Data) -> String {
    data.base64EncodedString()
      .replacingOccurrences(of: "+", with: "-")
      .replacingOccurrences(of: "/", with: "_")
      .replacingOccurrences(of: "=", with: "")
  }

  static func base64URLDecoded(_ value: String) -> Data? {
    var base64 =
      value
      .replacingOccurrences(of: "-", with: "+")
      .replacingOccurrences(of: "_", with: "/")
    base64 += String(repeating: "=", count: (4 - base64.count % 4) % 4)
    return Data(base64Encoded: base64)
  }

  private static func associatedData(messageID: String, createdAt: Int, expiresAt: Int) -> Data {
    Data("\(schema)|\(messageID)|\(createdAt)|\(expiresAt)".utf8)
  }
}
